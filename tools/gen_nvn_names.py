#!/usr/bin/env python3
"""names.txt (one NVN function name per line, in the order of the slot table) -> a C file defining nvn_names[]."""
import sys
names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_nvn_names.py from names.txt; do not edit\n#include "nvn_count.h"\n')
    f.write(f'_Static_assert({len(names)} == NVN_NFUNC, "names.txt and NVN_NFUNC disagree");\n')
    f.write('const char *nvn_names[NVN_NFUNC] = {\n' + ''.join(f'    "{n}",\n' for n in names) + '};\n')
