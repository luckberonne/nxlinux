#!/usr/bin/env python3
"""Generates the AArch32 call signatures of the NVN functions from src/gfx/nvn/nvn_protos.h (nvn.h's prototypes).

  gen_nvn_sig32.py nvn_protos.h out.inc

Each function becomes a line {"nvnName", "params", 'return'} for svc32.c. Parameter and return kinds: 'i' one word (an integer, a pointer, an enum), 'x' a 64-bit integer (a core register
pair, even-aligned), 'f' a float and 'd' a double (hard-float: the VFP registers s0../d0..), 'v' no return value. NVNtextureHandle, NVNimageHandle, NVNcommandHandle, NVNbufferAddress
and NVNtextureAddress are 64-bit; every other typedef is one word, as on the 32-bit process."""
import re, sys

WIDE = {'uint64_t', 'int64_t', 'NVNtextureHandle', 'NVNimageHandle', 'NVNcommandHandle', 'NVNbufferAddress', 'NVNtextureAddress', 'NVNcounterData64', 'unsigned long long', 'long long'}

def kind(t):
    t = t.strip()
    t = re.sub(r'\b(const|volatile|struct)\b', '', t).strip()
    if '*' in t or '[' in t: return 'i'
    if t == 'float': return 'f'
    if t == 'double': return 'd'
    if t in WIDE: return 'x'
    return 'i'

def split_params(s):
    out, depth, cur = [], 0, ''
    for c in s:
        if c == '(': depth += 1
        if c == ')': depth -= 1
        if c == ',' and depth == 0: out.append(cur); cur = ''
        else: cur += c
    if cur.strip(): out.append(cur)
    return out

def main(src, dst):
    text = re.sub(r'\s+', ' ', open(src).read())
    rows = []
    for m in re.finditer(r'typedef ([^;]*?) \(\*NVNT_(\w+)\)\((.*?)\);', text):
        ret, name, params = m.groups()
        ps = [p.strip() for p in split_params(params)]
        if ps == ['void'] or ps == ['']: ps = []
        sig = ''.join(kind(re.sub(r'\b\w+$', '', p) if re.search(r'[\w\]]\s+\w+$', p) and '*' not in p.split()[-1] and len(p.split()) > 1 and not p.rstrip().endswith('*') else p) for p in ps)
        r = 'v' if ret.strip() == 'void' else kind(ret)
        rows.append((name, sig, r))
    with open(dst, 'w') as f:
        f.write('// Generated by tools/gen_nvn_sig32.py from nvn_protos.h; do not edit.\n')
        for name, sig, r in rows: f.write('{"%s", "%s", \'%s\'},\n' % (name, sig, r))
    print(f'{dst}: {len(rows)} functions')

if __name__ == '__main__':
    if len(sys.argv) != 3: sys.exit(__doc__)
    main(*sys.argv[1:])
